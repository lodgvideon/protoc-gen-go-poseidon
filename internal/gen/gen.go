package gen

import (
	"path"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// Run generates one file per input file that declares at least one service.
func Run(p *protogen.Plugin, cfg Config) error {
	if err := cfg.Validate(); err != nil {
		return err
	}
	// One nameset per OUTPUT PACKAGE, not per file, and it outlives the loop.
	//
	// Several .proto files routinely route into one Go package — that is what
	// go_package is for — and their generated identifiers share that package's
	// scope. A per-file set cannot see across the boundary, so `service Foo_Bar`
	// with method `Baz` in one file and `service Foo` with method `Bar_Baz` in
	// another both emit Foo_Bar_Baz_FullMethodName, generation reports success,
	// and the user's build fails with "redeclared in this block" naming neither
	// .proto. protoc-gen-go on the same inputs is clean, so the blame lands
	// here.
	sets := map[string]*nameset{}
	var order []string

	for _, f := range p.Files {
		// p.Files carries transitive imports too; only the files protoc asked
		// for may be generated.
		if !f.Generate {
			continue
		}
		// This guard MUST precede NewGeneratedFile. That call appends to the
		// plugin's file list and Response reads every non-skipped entry back
		// through the Go parser, so an empty buffer with a .go name aborts the
		// whole run with "expected 'package', found 'EOF'".
		if len(f.Services) == 0 {
			continue
		}
		if err := generateFile(p, f, cfg, sets, &order); err != nil {
			return err
		}
	}

	// Reported after every file, so one run names every collision rather than
	// making the user regenerate per fix. In declaration order, so the message
	// does not shuffle between runs.
	for _, k := range order {
		if err := sets[k].err(); err != nil {
			return err
		}
	}
	return nil
}

// fileGen carries the per-file state the emitters share.
type fileGen struct {
	g     *protogen.GeneratedFile
	f     *protogen.File
	cfg   Config
	pkgs  runtimePackages
	names *nameset
}

// generateFile emits the poseidon client file for f.
func generateFile(p *protogen.Plugin, f *protogen.File, cfg Config,
	sets map[string]*nameset, order *[]string) error {
	// path, not filepath: CodeGeneratorResponse file names are always
	// slash-separated, including on Windows.
	dir, base := path.Split(f.GeneratedFilenamePrefix)
	filename := path.Join(dir, cfg.PackageSuffix, base) + "_poseidon.pb.go"
	importPath := protogen.GoImportPath(path.Join(string(f.GoImportPath), cfg.PackageSuffix))

	names, seen := sets[string(importPath)]
	if !seen {
		names = newNameset(string(importPath))
		sets[string(importPath)] = names
		*order = append(*order, string(importPath))
	}

	x := &fileGen{
		g:     p.NewGeneratedFile(filename, importPath),
		f:     f,
		cfg:   cfg,
		pkgs:  cfg.packages(),
		names: names,
	}

	x.header(p)
	for _, s := range f.Services {
		if err := checkService(s, cfg.Callers); err != nil {
			return err
		}
		x.service(s)
	}
	// Conflicts are NOT reported here. The set is shared with every other file
	// in this output package, and a file generated before its colliding sibling
	// would otherwise pass.
	return nil
}

// header emits the generated-file marker, the versions block and the package
// clause.
func (x *fileGen) header(p *protogen.Plugin) {
	g := x.g
	// The marker Go tooling matches is exactly this shape, as a line comment on
	// its own line before the package clause.
	g.P("// Code generated by protoc-gen-go-poseidon. DO NOT EDIT.")
	g.P("// versions:")
	g.P("// - protoc-gen-go-poseidon v", x.cfg.PluginVersion)
	g.P("// - protoc                 ", protocVersion(p))
	g.P("// source: ", x.f.Desc.Path())
	g.P()
	g.P("package ", x.cfg.PackageSuffix)
	g.P()
	g.P("// This is a compile-time assertion that this generated file is compatible")
	g.P("// with the pgrpc runtime it is being compiled against.")
	g.P("const _ = ", x.pkgs.pgrpc.Ident("SupportPackageIsVersion1"))
	g.P()
}

// protocVersion renders the compiler version, or "(unknown)" when the request
// carries none — which is the case under buf and in hand-built test requests.
// The line is emitted either way, so a buf golden and a protoc golden differ by
// its content rather than by its presence.
func protocVersion(p *protogen.Plugin) string {
	v := p.Request.GetCompilerVersion()
	if v == nil {
		return "(unknown)"
	}
	var sb strings.Builder
	sb.WriteString("v")
	sb.WriteString(strconv.Itoa(int(v.GetMajor())))
	sb.WriteString(".")
	sb.WriteString(strconv.Itoa(int(v.GetMinor())))
	sb.WriteString(".")
	sb.WriteString(strconv.Itoa(int(v.GetPatch())))
	if s := v.GetSuffix(); s != "" {
		sb.WriteString("-")
		sb.WriteString(s)
	}
	return sb.String()
}

// leading renders a .proto leading comment for emission, or "" when there is
// none. Comments.String already carries its "//" prefixes and a trailing
// newline; g.P adds its own, so the trailing one is trimmed.
func leading(c protogen.Comments) string {
	return defuseDirectives(strings.TrimSuffix(c.String(), "\n"))
}

// doc emits our own doc line followed by the .proto comment, if any.
func (x *fileGen) doc(own string, c protogen.Comments) {
	x.g.P("// ", own)
	if s := leading(c); s != "" {
		x.g.P("//")
		x.g.P(s)
	}
}

// shapeDoc describes a method's call shape, for a method with no .proto
// comment of its own.
func shapeDoc(m *protogen.Method) string {
	switch {
	case m.Desc.IsStreamingClient() && m.Desc.IsStreamingServer():
		return " is the bidirectional shape: a stream each way, independently driven."
	case m.Desc.IsStreamingServer():
		return " is the server-streaming shape: one request, a stream of replies."
	case m.Desc.IsStreamingClient():
		return " is the client-streaming shape: a stream of requests, one reply."
	default:
		return " is the unary shape: one request, one reply."
	}
}

// methodDoc emits a method's doc comment: the .proto comment when it has one,
// otherwise a description of its call shape.
func (x *fileGen) methodDoc(m *protogen.Method) {
	if s := leading(m.Comments.Leading); s != "" {
		x.g.P(s)
		return
	}
	x.g.P("// ", m.GoName, shapeDoc(m))
}

// fullMethod is the wire path. It is built from the DESCRIPTOR names, never
// from the Go names: the two differ for anything with an underscore, and this
// is what reaches the server.
func fullMethod(s *protogen.Service, m *protogen.Method) string {
	return "/" + string(s.Desc.FullName()) + "/" + string(m.Desc.Name())
}

// strconvQuote renders a Go string literal. The method paths it quotes come
// from descriptors, which cannot contain a quote or a backslash, but quoting
// them properly costs nothing and keeps a malformed descriptor from producing
// output that does not parse.
func strconvQuote(s string) string { return strconv.Quote(s) }
